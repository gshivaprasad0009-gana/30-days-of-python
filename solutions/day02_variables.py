"""
Day 2 — Variables and types.

A variable is a named box holding a value. Python figures out the type itself.
"""

name = "Shiva Prasad"      # str  — text
age = 20                   # int  — whole number
marks = 85.5               # float — decimal number
branch = "ECE"             # str

print("Name:", name)
print("Age:", age)
print("Marks:", marks)
print("Branch:", branch)

# type() tells you what kind of value something is
print("Type of name:", type(name))
print("Type of age:", type(age))
print("Type of marks:", type(marks))
